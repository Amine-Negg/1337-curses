#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*sub;
	size_t	i;
	size_t	ln;

	if (!s)
		return (NULL);
	ln = ft_strlen(s);
	if (start >= ln)
		return (ft_strdup(""));
	if (len > ln - start)
		len = ln - start;
	sub = malloc(len + 1);
	if (!sub)
		return (NULL);
	i = 0;
	while (i < len)
	{
		sub[i] = s[start + i];
		i++;
	}
	sub[i] = '\0';
	return (sub);
}

